// The overview: the database at a glance (its tables, rows, columns and relationships), a card per table with how
// many rows it has, the tables by size, and the newest rows of those that say what's newest.
import { Value } from "./cells.tsx";
import { appName, fieldNamed, rowCounts, tables, theDatabase, type RowCount } from "./config.ts";
import { useQuery, useReferences } from "./data.ts";
import { formatCount, formatInteger, keyText, rowLabel, rowPath } from "./format.ts";
import { Icon } from "./icons.tsx";
import { Link, navigate } from "./router.tsx";
import type { Field, Paged, Row, Table } from "./types.ts";
import { Badge, Card, Crumbs, EmptyState, Skeleton, cx } from "./ui.tsx";

function Stat({ icon, label, value, note }: { icon: string; label: string; value: string | undefined; note: string }) {
  return (
    <div className="stat">
      <div className="stat__top"><span className="stat__icon"><Icon name={icon} size={15} /></span>{label}</div>
      <div className="stat__value">{value ?? <Skeleton width={64} height={26} />}</div>
      <div className="stat__note">{note}</div>
    </div>
  );
}

/** The newest rows of a table: by what it says is newest, first. */
function Recent({ table, count }: { table: Table; count: number }) {
  const options = { sort: table.recent, desc: true, pageSize: 5 };
  const query = useQuery<Paged<Row>>(`${table.name}:list:${JSON.stringify(options)}`, () => table.api.list(options));
  const rows = query.shown?.items ?? [];
  const references = useReferences(table, rows);
  const recent = table.recent ? fieldNamed(table, table.recent) : undefined;
  // what to show beside each row's name: its newest-by field where that's a date, or its first other column
  const aside: Field | undefined = recent && (recent.kind === "date" || recent.kind === "datetime") ? recent
    : table.columns.map((name) => fieldNamed(table, name)).find((field) => field && !field.key && !table.display.includes(field.name));
  return (
    <Card title={table.title} icon={table.icon} count={count} flush className="recent"
      actions={<Link href={`/${table.name}?sort=${encodeURIComponent(table.recent ?? "")}&desc=1`} className="card__link">View all<Icon name="arrow-right" size={13} /></Link>}>
      <ul className="recent__list">
        {query.loading && !query.shown && [0, 1, 2, 3].map((i) => <li key={i} className="recent__row"><Skeleton width={28} height={28} radius={8} /><Skeleton width={`${35 + i * 9}%`} /></li>)}
        {rows.map((row) => (
          <li key={keyText(table, row)}>
            <Link href={rowPath(table, row)} className="recent__row">
              <span className="recent__avatar" aria-hidden="true">{initials(rowLabel(table, row))}</span>
              <span className="recent__text">
                <span className="recent__label">{rowLabel(table, row)}</span>
                <span className="recent__key is-mono">{keyText(table, row)}</span>
              </span>
              {aside && <span className="recent__aside"><Value table={table} field={aside} row={row} referred={references.of(aside, row)} /></span>}
            </Link>
          </li>
        ))}
      </ul>
    </Card>
  );
}

const initials = (text: string) => {
  const words = text.replace(/^#/, "").split(/[\s_-]+|(?<=[a-z])(?=[A-Z])/).filter(Boolean);
  return (words.length > 1 ? words[0][0] + words[1][0] : (words[0] ?? "?").slice(0, 2)).toUpperCase();
};

export function Dashboard() {
  const all = tables();
  const database = theDatabase();
  const counts = useQuery<RowCount[]>("counts", rowCounts, 5000);
  const countOf = (table: Table) => counts.shown?.find((count) => count.table === table.name)?.rows;
  const rows = counts.shown ? all.reduce((sum, table) => sum + (countOf(table) ?? 0), 0) : undefined;
  const columns = all.reduce((sum, table) => sum + table.fields.length, 0);
  const relationships = all.reduce((sum, table) => sum + table.references.length, 0);
  const largest = Math.max(1, ...all.map((table) => countOf(table) ?? 0));
  const bySize = [...all].filter((table) => (countOf(table) ?? 0) > 0).sort((a, b) => (countOf(b) ?? 0) - (countOf(a) ?? 0)).slice(0, 8);
  const recent = all.filter((table) => table.recent && (countOf(table) ?? 0) > 0).sort((a, b) => (countOf(b) ?? 0) - (countOf(a) ?? 0)).slice(0, 2);
  const empty = all.filter((table) => counts.shown && countOf(table) === 0);

  return (
    <div className="page page--dashboard">
      <Crumbs items={[{ label: appName(), href: "/" }, { label: "Overview" }]} />
      <header className="hero">
        <div className="hero__mark"><Icon name="database" size={22} /></div>
        <div>
          <h1 className="hero__title">{appName()}</h1>
          <p className="hero__text">
            A {database.provider} database: {all.length} tables, every one with a list, a page per row and a form, generated by CodeSmith Generator.
          </p>
        </div>
      </header>

      <div className="stats">
        <Stat icon="table" label="Tables" value={formatInteger(all.length)} note={`${all.filter((t) => t.key.length).length} with a key`} />
        <Stat icon="rows" label="Rows" value={rows === undefined ? undefined : formatCount(rows)} note={empty.length ? `${empty.length} ${empty.length === 1 ? "table is" : "tables are"} empty` : "in every table"} />
        <Stat icon="columns" label="Columns" value={formatInteger(columns)} note={`${formatInteger(Math.round(columns / Math.max(1, all.length)))} a table, on average`} />
        <Stat icon="branch" label="Relationships" value={formatInteger(relationships)} note="foreign keys between them" />
      </div>

      <div className="dashboard-columns">
        <div className="dashboard-stack">
          <Card title="Rows by table" icon="rows" className="bars-card">
            {counts.loading && !counts.shown
              ? <div className="bars">{[0, 1, 2, 3, 4].map((i) => <div key={i} className="bar"><Skeleton width={90} /><Skeleton width={`${80 - i * 14}%`} height={8} /></div>)}</div>
              : (
                <ol className="bars" aria-label="Rows in each table, largest first">
                  {bySize.map((table) => {
                    const count = countOf(table) ?? 0;
                    return (
                      <li key={table.name}>
                        <button type="button" className="bar" onClick={() => void navigate(`/${table.name}`)} title={`${table.title}: ${formatInteger(count)} ${count === 1 ? "row" : "rows"}`}>
                          <span className="bar__label">{table.title}</span>
                          <span className="bar__track"><span className={cx("bar__fill", count === 0 && "is-zero")} style={{ width: `${count ? Math.max(1.5, (count / largest) * 100) : 0}%` }} /></span>
                          <span className="bar__value">{formatInteger(count)}</span>
                        </button>
                      </li>
                    );
                  })}
                </ol>
              )}
          </Card>
          {empty.length > 0 && (
            <Card title="Empty tables" icon="inbox" className="empty-tables">
              <div className="empty-tables__list">
                {empty.map((table) => (
                  <Link key={table.name} href={`/${table.name}`} className="empty-tables__item">
                    <Icon name={table.icon} size={14} />{table.title}
                  </Link>
                ))}
              </div>
            </Card>
          )}
        </div>
        <div className="recent-stack">
          {recent.map((table) => <Recent key={table.name} table={table} count={countOf(table) ?? 0} />)}
          {counts.shown && recent.length === 0 && (
            <Card title="Newest rows" icon="clock"><EmptyState compact icon="clock" title="Nothing to show">No table with rows says which are newest.</EmptyState></Card>
          )}
        </div>
      </div>

      <section className="dashboard-section">
        <h2 className="section-title">Tables</h2>
        <div className="table-cards">
          {all.map((table) => {
            const count = countOf(table);
            return (
              <Link key={table.name} href={`/${table.name}`} className="table-tile">
                <div className="table-tile__top">
                  <span className="table-tile__icon"><Icon name={table.icon} size={16} /></span>
                  <span className="table-tile__title">{table.title}</span>
                  <Icon name="arrow-up-right" size={14} className="table-tile__go" />
                </div>
                <div className="table-tile__count">{count === undefined ? <Skeleton width={40} height={22} /> : formatCount(count)}<span>{count === 1 ? "row" : "rows"}</span></div>
                <div className="table-tile__meter" aria-hidden="true"><span style={{ width: `${count ? Math.max(3, (count / largest) * 100) : 0}%` }} /></div>
                <div className="table-tile__meta">
                  {table.fields.length} columns{table.references.length > 0 && <> · refers to {table.references.map((r) => r.label.toLowerCase()).join(", ")}</>}
                </div>
              </Link>
            );
          })}
        </div>
      </section>

      {counts.error !== undefined && !counts.shown && <Badge tone="danger">Couldn't count the rows</Badge>}
    </div>
  );
}
