CREATE OR REPLACE PROCEDURE GET_PRODUCTS_BY_CATEGORY(P_CATEGORYID IN VARCHAR2, P_RESULTS OUT SYS_REFCURSOR) AS
BEGIN
  OPEN P_RESULTS FOR SELECT PRODUCTID, NAME, DESCN FROM PRODUCT WHERE CATEGORYID = P_CATEGORYID ORDER BY NAME;
END;
