-- PetShop for Oracle: a subset of PetShop.sql (SQL Server's), for the samples, as its own user:
-- sqlplus petshop/<password>@<service> @PetShop.oracle.sql
CREATE TABLE CATEGORY (
  CATEGORYID VARCHAR2(10) NOT NULL,
  NAME VARCHAR2(80) NULL,
  DESCN VARCHAR2(255) NULL,
  CONSTRAINT PK_CATEGORY PRIMARY KEY (CATEGORYID)
)
/
CREATE TABLE SUPPLIER (
  SUPPID NUMBER(10) NOT NULL,
  NAME VARCHAR2(80) NULL,
  STATUS VARCHAR2(2) NOT NULL,
  CITY VARCHAR2(80) NULL,
  ZIP VARCHAR2(5) NULL,
  CONSTRAINT PK_SUPPLIER PRIMARY KEY (SUPPID)
)
/
CREATE TABLE PRODUCT (
  PRODUCTID VARCHAR2(10) NOT NULL,
  CATEGORYID VARCHAR2(10) NOT NULL,
  NAME VARCHAR2(80) NULL,
  DESCN VARCHAR2(255) NULL,
  IMAGE VARCHAR2(80) NULL,
  CONSTRAINT PK_PRODUCT PRIMARY KEY (PRODUCTID),
  CONSTRAINT FK_PRODUCT_CATEGORY FOREIGN KEY (CATEGORYID) REFERENCES CATEGORY (CATEGORYID)
)
/
CREATE INDEX IX_PRODUCT_CATEGORY ON PRODUCT (CATEGORYID)
/
CREATE TABLE ITEM (
  ITEMID VARCHAR2(10) NOT NULL,
  PRODUCTID VARCHAR2(10) NOT NULL,
  LISTPRICE NUMBER(10,2) NULL,
  UNITCOST NUMBER(10,2) NULL,
  SUPPLIER NUMBER(10) NULL,
  STATUS VARCHAR2(2) NULL,
  NAME VARCHAR2(80) NULL,
  CONSTRAINT PK_ITEM PRIMARY KEY (ITEMID),
  CONSTRAINT UQ_ITEM_NAME UNIQUE (NAME),
  CONSTRAINT FK_ITEM_PRODUCT FOREIGN KEY (PRODUCTID) REFERENCES PRODUCT (PRODUCTID),
  CONSTRAINT FK_ITEM_SUPPLIER FOREIGN KEY (SUPPLIER) REFERENCES SUPPLIER (SUPPID)
)
/
CREATE TABLE ORDERS (
  ORDERID NUMBER(10) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  USERID VARCHAR2(20) NOT NULL,
  ORDERDATE DATE NOT NULL,
  SHIPCITY VARCHAR2(80) NOT NULL,
  TOTALPRICE NUMBER(10,2) NOT NULL,
  LOCALE VARCHAR2(20) DEFAULT 'en-US' NOT NULL,
  CONSTRAINT PK_ORDERS PRIMARY KEY (ORDERID)
)
/
CREATE TABLE LINEITEM (
  ORDERID NUMBER(10) NOT NULL,
  LINENUM NUMBER(10) NOT NULL,
  ITEMID VARCHAR2(10) NOT NULL,
  QUANTITY NUMBER(10) NOT NULL,
  UNITPRICE NUMBER(10,2) NOT NULL,
  CONSTRAINT PK_LINEITEM PRIMARY KEY (ORDERID, LINENUM),
  CONSTRAINT FK_LINEITEM_ORDER FOREIGN KEY (ORDERID) REFERENCES ORDERS (ORDERID),
  CONSTRAINT FK_LINEITEM_ITEM FOREIGN KEY (ITEMID) REFERENCES ITEM (ITEMID)
)
/
