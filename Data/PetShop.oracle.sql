CREATE VIEW PRODUCTCATEGORY AS
SELECT p.PRODUCTID, p.NAME AS PRODUCTNAME, c.CATEGORYID, c.NAME AS CATEGORYNAME
FROM PRODUCT p INNER JOIN CATEGORY c ON c.CATEGORYID = p.CATEGORYID
